const { chromium } = require('playwright')
const fs = require('fs')
const [SP, OUT] = process.argv.slice(2)
// --replay: the report already holds the recorded real verdicts, plan and poster (evidence/replay_real_ui.py),
// so the two buttons that call models are not pressed. Owner confirm/reject clicks still go through the UI.
const REPLAY = process.argv.includes('--replay')
const rep = JSON.parse(fs.readFileSync(SP + '/report.json'))
const BASE = process.env.APP || 'http://localhost:8788'
const NOSTICKY = '.nav{position:static !important} *{animation:none !important;transition:none !important}'
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 2 })
  await ctx.addInitScript(([id, t]) => { localStorage.setItem('fmd_owner_' + id, t) }, [rep.report_id, rep.owner_token])
  const p = await ctx.newPage()
  const errs = []
  p.on('pageerror', e => errs.push(e.message))
  await p.goto(`${BASE}/#/r/${rep.report_id}`, { waitUntil: 'networkidle' })
  await p.addStyleTag({ content: NOSTICKY })
  await p.waitForTimeout(800)
  await (await p.$$('section.card'))[0].screenshot({ path: `${OUT}/real-01-footage-sam-tracks.jpg`, type: 'jpeg', quality: 86 })
  let t0 = Date.now()
  if (!REPLAY) await p.click('button:has-text("Run matcher")')
  await p.waitForSelector('.sighting', { timeout: 240000 })
  const matchS = ((Date.now() - t0) / 1000).toFixed(1)
  await p.waitForTimeout(500)
  await (await p.$$('section.card'))[1].screenshot({ path: `${OUT}/real-02-spark-match-ranked.jpg`, type: 'jpeg', quality: 86 })
  const top = p.locator('.sighting').first()
  const topText = await top.innerText()
  if (!/\d+% match/.test(topText) || /not a match/.test(topText)) throw new Error('top card is not a Spark match: ' + topText.slice(0, 120))
  await top.locator('button:has-text("That\'s Biscuit")').click()
  await p.waitForSelector('text=confirmed')
  const rest = p.locator('button:has-text("Not them")')
  while (await rest.count()) { await rest.first().click(); await p.waitForTimeout(500) }
  t0 = Date.now()
  if (!REPLAY) await p.click('button:has-text("Generate plan + poster")')
  await p.waitForSelector('img.poster', { timeout: 300000 })
  const planS = ((Date.now() - t0) / 1000).toFixed(1)
  await p.waitForTimeout(1500)
  await (await p.$$('section.card'))[2].screenshot({ path: `${OUT}/real-03-spark-plan-muse-poster.jpg`, type: 'jpeg', quality: 86 })
  await p.screenshot({ path: `${OUT}/real-00-console-full.jpg`, type: 'jpeg', quality: 86, fullPage: true })
  await p.goto(`${BASE}/#/r/${rep.report_id}/share`, { waitUntil: 'networkidle' })
  await p.addStyleTag({ content: NOSTICKY })
  await p.waitForSelector('img.poster')
  await p.waitForTimeout(1200)
  await p.screenshot({ path: `${OUT}/real-04-share-page.jpg`, type: 'jpeg', quality: 86, fullPage: true })
  const c2 = await b.newContext({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 2 })
  const p2 = await c2.newPage()
  await p2.goto(`${BASE}/#/r/${rep.report_id}`, { waitUntil: 'networkidle' })
  await p2.addStyleTag({ content: NOSTICKY })
  await p2.waitForTimeout(800)
  await p2.screenshot({ path: `${OUT}/access-stranger-view-only.jpg`, type: 'jpeg', quality: 86 })
  const s = await (await fetch(`${BASE}/api/reports/${rep.report_id}`)).json()
  fs.writeFileSync(SP + '/real_state.json', JSON.stringify(s, null, 2))
  console.log(JSON.stringify({ matchS, planS, matcher: s.matcher_model, cost: s.cost, matches: s.matches.map(m => [m.clip_id, m.object_id, m.is_match, m.score, m.confirmed]), plan: s.next_search && s.next_search.headline, errs }, null, 1))
  await b.close()
})().catch(e => { console.error('FAIL', e.message); process.exit(1) })
