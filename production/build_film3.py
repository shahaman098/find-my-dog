"""Build Film 3's timeline data (production/film3/data.js).
    python3 production/build_film3.py production/out/12_raw_evidence/take_01
"""
import json, os, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TAKE = os.path.abspath(sys.argv[1])
OUT = os.path.join(ROOT, 'production', 'film3')
A = os.path.join(OUT, 'assets')
os.makedirs(A, exist_ok=True)
VOICE = os.path.join(ROOT, 'production', 'out', 'voice', '03_cinematic_product_ad_60s')
script = json.load(open(os.path.join(ROOT, 'production', 'scripts', 'film3.json')))
f1 = json.loads(open(os.path.join(ROOT, 'production', 'film1', 'data.js')).read()[len('window.DATA = '):].rstrip().rstrip(';'))

# concept stills -> 3840-wide JPEGs (Lanczos), generated by Muse Image (production/concept_images.mjs)
for name in ['gate', 'street', 'doorstep', 'home']:
    dst = os.path.join(A, f'{name}.jpg')
    if not os.path.exists(dst):
        im = Image.open(os.path.join(ROOT, 'production', 'assets', 'concept', f'{name}_1536x1024.webp')).convert('RGB')
        im.resize((3840, int(3840 * im.height / im.width)), Image.LANCZOS).save(dst, quality=92)
# the real top match card, cropped from the take's 4K still of the matches section
st = Image.open(os.path.join(TAKE, 'still_matches.png')).convert('RGB')
st.save(os.path.join(A, 'matches_still.jpg'), quality=92)

ev = json.load(open(os.path.join(TAKE, 'events.json')))
E = {}
for e in ev['events']:
    E.setdefault(e['name'], e['t'])
rec0 = E['screen_recording_started']
V = lambda k, d=0.0: round(E[k] - rec0 + d, 3)

voice, captions, words_by = [], [], {}
for sc in script['scenes']:
    if not sc['text']:
        words_by[sc['id']] = []; continue
    w = json.load(open(os.path.join(VOICE, f"{sc['id']}.words.json")))
    at = sc['start'] + 0.4
    voice.append({'scene': sc['id'], 'file': os.path.join(VOICE, f"{sc['id']}.wav"), 'at': at, 'duration': w['duration']})
    words = [{'w': x['word'], 's': round(at + x['start'], 3), 'e': round(at + x['end'], 3)} for x in w['words']]
    words_by[sc['id']] = words
    line, start = [], None
    for i, x in enumerate(words):
        if not line: start = x['s']
        line.append(x)
        text = ' '.join(y['w'] for y in line); nxt = words[i + 1]['w'] if i + 1 < len(words) else None
        if len(text) > 34 or x['w'][-1] in '.?!' or nxt is None or len(text + ' ' + (nxt or '')) > 40:
            captions.append({'s': start, 'e': x['e'] + 0.25, 'text': text, 'words': line}); line = []
for a_, b_ in zip(captions, captions[1:]):
    a_['e'] = round(min(a_['e'], b_['s'] - 0.02), 3)

s5 = next(s for s in script['scenes'] if s['id'] == '05_reveal')
data = {
    'fps': 24, 'duration': script['duration'], 'scenes': [{k: s[k] for k in ['id', 'start', 'end', 'text']} for s in script['scenes']],
    'words': words_by, 'captions': captions,
    'take': {**f1['take'], 'dir': os.path.relpath(os.path.join(TAKE, 'take_frames'), OUT)},
    'reveal_map': [[s5['start'] + 0.6, V('matches_visible', 0.5)], [s5['end'] - 0.4, V('poster_visible', 1.5)]],
    'arch_svg': open(os.path.join(ROOT, 'production', '08_architecture_diagram.svg')).read(),
    'voice': voice,
}
open(os.path.join(OUT, 'data.js'), 'w').write('window.DATA = ' + json.dumps(data) + ';\n')
json.dump({'voice': voice, 'captions': captions}, open(os.path.join(OUT, 'audio_plan.json'), 'w'), indent=1)
print('film3 data:', len(captions), 'captions; reveal map', data['reveal_map'])
